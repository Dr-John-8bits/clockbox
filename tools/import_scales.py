#!/usr/bin/env python3
"""Import the scale table of the Monades / Rhizome FM-1 synths into the clockbox.

usage: python3 tools/import_scales.py <path to monades/app/dsp/scale_table.inc>

Writes:
  scales.h          for the firmware (masks and microtonal degrees in PROGMEM)
  site/scales.js    for the screen (names, families, browsing order, data)
"""
import json, os, re, sys

src = open(sys.argv[1], encoding="utf-8").read()
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

families = re.findall(r'"([^"]+)"', re.search(r"scale_families\[\]=\{(.*?)\};", src, re.S).group(1))
twelve = [(n, int(f), int(u, 16), int(d, 16))
          for n, f, u, d in re.findall(r'\{"([^"]+)",(\d+),(0x[0-9a-f]+),(0x[0-9a-f]+)\}', src)]
order = [int(x) for x in re.search(r"scale_order\[\]=\{([^}]*)\}", src).group(1).split(",")]
micro = []
for n, f, c, period, degs in re.findall(r'\{"([^"]+)",(\d+),(\d+),([\d.]+)f,\{([^}]*)\}\}', src):
    d = [float(x.rstrip("f")) for x in degs.split(",") if x.strip()]
    assert len(d) == int(c), n
    micro.append((n, int(f), float(period), d))
enum = dict(re.findall(r"(SCALE_\w+)=(\d+)", src))
n_twelve, n_all, custom = int(enum["SCALE_TWELVE"]), int(enum["SCALE_COUNT"]), int(enum["SCALE_CUSTOM"])
assert len(twelve) == n_twelve and n_twelve + len(micro) == n_all, (len(twelve), len(micro))

degrees, offsets = [], []
for _, _, _, d in micro:
    offsets.append(len(degrees))
    degrees += [round(x * 10) for x in d]

h = ["// Generated by tools/import_scales.py from the Monades / Rhizome scale table. Do not edit.",
     "// 12-tone scales: bit k of the mask = k semitones above the root (up = ascending, down = descending).",
     "// Microtonal scales: degrees above the root in 0.1 cent, period in 0.1 cent.",
     "#pragma once", "#include <avr/pgmspace.h>", "",
     f"const uint8_t SCALE_COUNT = {n_all}, SCALE_TWELVE = {n_twelve}, SCALE_CUSTOM = {custom};",
     "const uint16_t SCALE_MASK[SCALE_TWELVE][2] PROGMEM = {"]
h += ["  {0x%03x, 0x%03x},  // %s" % (u, d, n) for n, _, u, d in twelve] + ["};", ""]
h += [f"const uint8_t MICRO_COUNT = {len(micro)};",
      "const uint8_t MICRO_DEGREES[MICRO_COUNT] PROGMEM = {" + ", ".join(str(len(d)) for *_, d in micro) + "};",
      "const uint16_t MICRO_PERIOD[MICRO_COUNT] PROGMEM = {" + ", ".join(str(round(p * 10)) for _, _, p, _ in micro) + "};",
      "const uint16_t MICRO_OFFSET[MICRO_COUNT] PROGMEM = {" + ", ".join(map(str, offsets)) + "};",
      "const uint16_t MICRO_CENTS[] PROGMEM = {"]
for i in range(0, len(degrees), 12):
    h.append("  " + ", ".join(map(str, degrees[i:i + 12])) + ",")
h += ["};", ""]
open(os.path.join(root, "scales.h"), "w").write("\n".join(h))

js = {"families": families, "order": order,
      "scales": [{"name": n, "family": f, "up": u, "down": d} for n, f, u, d in twelve] +
                [{"name": n, "family": f, "period": p, "cents": d} for n, f, p, d in micro],
      "custom": custom}
open(os.path.join(root, "site", "scales.js"), "w").write(
    "// Generated by tools/import_scales.py from the Monades / Rhizome scale table. Do not edit.\n"
    "window.CLOCKBOX_SCALES = " + json.dumps(js, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"{n_twelve} twelve-tone + {len(micro)} microtonal scales, {len(degrees)} micro degrees, {len(order)} in browsing order")
